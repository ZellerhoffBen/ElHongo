/**
 * Derivative generation for the layered hero artwork.
 *
 * The masters in `assets/hero/` are two 2038x2000 RGBA PNGs of ~2 MB each, and
 * they are pixel-identical outside a 67x38 transparent hole over the eye. Only
 * one of them is therefore worth serving at full size; the other survives as a
 * 160x96 crop that clips the pupil back to the drawn socket.
 *
 * Writes the responsive AVIF/WebP ladder consumed by `EyeFollowerArt`, plus one
 * quantised PNG as the universal `<img src>` fallback.
 *
 * Run after replacing a master:  npm run build:hero
 */
import { createHash } from "node:crypto";
import { mkdir, readdir, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import {
  ARTWORK_SIZE,
  ARTWORK_WIDTHS,
  FALLBACK_WIDTH,
  SOCKET_WINDOW,
  getPupilTravelBounds,
} from "../lib/heroArtwork.ts";

const ROOT = path.resolve(import.meta.dirname, "..");
const SOURCE_DIR = path.join(ROOT, "assets/hero");
const OUTPUT_DIR = path.join(ROOT, "public/hero");
const MANIFEST_FILE = path.join(ROOT, "lib/heroAssets.generated.ts");

const kib = (bytes) => `${(bytes / 1024).toFixed(1)} KiB`;

/**
 * Content-addressed filenames. Regenerating the artwork changes every URL, so
 * `/hero/*` can be served `immutable` for a year without ever pinning a stale
 * plate in somebody's cache.
 */
async function emit(name, extension, buffer) {
  const digest = createHash("sha256").update(buffer).digest("hex").slice(0, 8);
  const file = `${name}.${digest}.${extension}`;
  await writeFile(path.join(OUTPUT_DIR, file), buffer);
  return `/hero/${file}`;
}

function assertGeometry() {
  const travel = getPupilTravelBounds();
  const window = {
    left: SOCKET_WINDOW.left,
    top: SOCKET_WINDOW.top,
    right: SOCKET_WINDOW.left + SOCKET_WINDOW.width,
    bottom: SOCKET_WINDOW.top + SOCKET_WINDOW.height,
  };

  if (
    travel.left < window.left ||
    travel.right > window.right ||
    travel.top < window.top ||
    travel.bottom > window.bottom
  ) {
    throw new Error(
      `SOCKET_WINDOW ${JSON.stringify(window)} does not contain the pupil travel ` +
        `${JSON.stringify(travel)} — the pupil would escape the mask.`,
    );
  }
}

async function build() {
  assertGeometry();

  await rm(OUTPUT_DIR, { recursive: true, force: true }).catch(() => {});
  await mkdir(OUTPUT_DIR, { recursive: true });

  const artworkMaster = path.join(SOURCE_DIR, "background_white_eye.png");
  const maskMaster = path.join(SOURCE_DIR, "vordergrund_mask.png");

  const { width, height } = await sharp(artworkMaster).metadata();
  if (width !== ARTWORK_SIZE.width || height !== ARTWORK_SIZE.height) {
    throw new Error(
      `Master is ${width}x${height} but lib/heroArtwork.ts declares ` +
        `${ARTWORK_SIZE.width}x${ARTWORK_SIZE.height}. Re-tune the eye constants.`,
    );
  }

  // The artwork layer is fully opaque, so dropping the alpha plane saves the
  // codec a channel it would otherwise carry at full resolution.
  const srcset = { avif: [], webp: [] };

  for (const targetWidth of ARTWORK_WIDTHS) {
    const resized = () =>
      sharp(artworkMaster)
        .removeAlpha()
        .resize({ width: targetWidth, withoutEnlargement: true });

    // q45/q72: compared against the master at the sizes this actually renders,
    // the hatching is indistinguishable, and the LCP image is ~27 KiB lighter.
    for (const [format, encode] of [
      ["avif", (pipeline) => pipeline.avif({ quality: 45, effort: 6 })],
      ["webp", (pipeline) => pipeline.webp({ quality: 72, effort: 6 })],
    ]) {
      const url = await emit(
        `artwork-${targetWidth}`,
        format,
        await encode(resized()).toBuffer(),
      );
      srcset[format].push(`${url} ${targetWidth}w`);
    }
  }

  const fallback = await emit(
    `artwork-${FALLBACK_WIDTH}`,
    "png",
    await sharp(artworkMaster)
      .removeAlpha()
      .resize({ width: FALLBACK_WIDTH, withoutEnlargement: true })
      .png({ compressionLevel: 9, palette: true, quality: 90 })
      .toBuffer(),
  );

  // Socket mask and pupil are exact pixel copies at native resolution — the
  // masters hold no more detail in this region than the crop does, and the
  // alpha edge that shapes the socket must not be touched by a lossy codec.
  // Lossless WebP, not PNG: same pixels, 8 KiB less, and it is fetched in the
  // same breath as the LCP image.
  const socketMask = await emit(
    "socket-mask",
    "webp",
    await sharp(maskMaster)
      .extract(SOCKET_WINDOW)
      .webp({ lossless: true, effort: 6 })
      .toBuffer(),
  );

  const pupil = await emit(
    "pupil",
    "png",
    await sharp(path.join(SOURCE_DIR, "pupil.png"))
      .png({ compressionLevel: 9 })
      .toBuffer(),
  );

  await writeFile(
    MANIFEST_FILE,
    [
      "// Generated by scripts/build-hero-assets.mjs — do not edit.",
      "// Filenames are content-addressed so /hero/* can be cached immutably.",
      "",
      "export const heroAssets = {",
      `  avifSrcSet: ${JSON.stringify(srcset.avif.join(", "))},`,
      `  webpSrcSet: ${JSON.stringify(srcset.webp.join(", "))},`,
      `  fallback: ${JSON.stringify(fallback)},`,
      `  socketMask: ${JSON.stringify(socketMask)},`,
      `  pupil: ${JSON.stringify(pupil)},`,
      "} as const;",
      "",
    ].join("\n"),
  );

  let total = 0;
  for (const file of (await readdir(OUTPUT_DIR)).sort()) {
    const { size } = await stat(path.join(OUTPUT_DIR, file));
    total += size;
    console.log(`${file.padEnd(34)} ${kib(size).padStart(12)}`);
  }

  const single = async (url) =>
    (await stat(path.join(ROOT, "public", url.slice(1)))).size;

  console.log(`\nfull ladder: ${kib(total)}`);
  console.log(
    `worst single load (2038 avif + mask + pupil): ` +
      `${kib(
        (await single(srcset.avif.at(-1).split(" ")[0])) +
          (await single(socketMask)) +
          (await single(pupil)),
      )}`,
  );
}

build().catch((error) => {
  console.error(error);
  process.exit(1);
});
